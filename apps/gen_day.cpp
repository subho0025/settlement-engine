#include "gen/day_gen.hpp"

using namespace std;

static void usage(){
    cerr << "usage: gen_day [--config FILE] [--seed N] [--set key=value]... [--out FILE] [--print-config]\n"
            "  --config FILE      generator settings, one 'key = value' per line; missing keys keep their defaults\n"
            "  --seed N           same as --set seed=N\n"
            "  --set key=value    override one setting (repeatable, applied after --config)\n"
            "  --out FILE         write the day file there (default: standard output)\n"
            "  --print-config     print the final settings and exit\n";
}

int main(int argc, char** argv){
    string config_path, out_path;
    vector<pair<string,string>> overrides;
    bool print_config = false;

    for(int i = 1; i < argc; i++){
        string a = argv[i];
        auto next = [&]() -> string {
            if(i + 1 >= argc){ usage(); exit(1); }
            return argv[++i];
        };
        if(a == "--config") config_path = next();
        else if(a == "--out") out_path = next();
        else if(a == "--seed") overrides.push_back({"seed", next()});
        else if(a == "--set"){
            string kv = next();
            size_t eq = kv.find('=');
            if(eq == string::npos){ cerr << "error: --set needs key=value\n"; return 1; }
            overrides.push_back({kv.substr(0, eq), kv.substr(eq + 1)});
        }
        else if(a == "--print-config") print_config = true;
        else if(a == "-h" || a == "--help"){ usage(); return 0; }
        else{ usage(); return 1; }
    }

    try{
        DayParams p;
        if(!config_path.empty()){
            ifstream in(config_path);
            if(!in) throw runtime_error("cannot open " + config_path);
            p = read_day_params(in);
        }
        for(const auto& [k, v] : overrides){
            set_day_param(p, k, v);
        }

        if(print_config){
            write_day_params(cout, p);
            return 0;
        }

        Day d = generate_day(p);

        ofstream file;
        if(!out_path.empty()){
            file.open(out_path);
            if(!file) throw runtime_error("cannot write " + out_path);
        }
        ostream& out = out_path.empty() ? cout : file;

        ostringstream cfg;
        write_day_params(cfg, p);
        istringstream lines(cfg.str());
        string line;
        out << "# generated by gen_day with these settings:\n";
        while(getline(lines, line)){
            if(!line.empty() && line[0] != '#'){
                out << "#   " << line << "\n";
            }
        }
        write_day(out, d);

        cerr << "gen_day: " << d.n << " banks, " << d.payments.size() << " payments, times 0.." << d.end
             << (out_path.empty() ? "" : " -> " + out_path) << "\n";
    }catch(const exception& e){
        cerr << "error: " << e.what() << "\n";
        return 1;
    }
    return 0;
}